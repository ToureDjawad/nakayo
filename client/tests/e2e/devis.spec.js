import { expect, test } from '@playwright/test'
import { seConnecter, verifierAccessibilite, verifierSansDefilementHorizontal } from './outils.js'

async function deconnecter(page) {
  await page.getByRole('button', { name: 'Se déconnecter' }).click()
  await page.waitForURL(/\/connexion|\/$/)
}

test.describe('Offre Plus sur devis (US-37)', () => {
  test('le développeur demande un devis, l’équipe propose un prix, le développeur le paie', async ({ page }) => {
    test.setTimeout(120_000)
    await seConnecter(page, 'valide@exemple.com')
    await page.waitForURL('/mon-compte')
    await page.getByRole('link', { name: 'Soumettre une app' }).click()
    await page.getByLabel('Nom de l’app').fill('Marché Afrique')
    await page.getByLabel('Nom du package').fill('bj.studioawa.marcheafrique')
    await page.getByLabel('Description').fill('Une app pour commander au marché de Dantokpa et se faire livrer.')
    await page.getByLabel('Lien d’inscription au test fermé').fill('https://play.google.com/apps/testing/bj.studioawa.marcheafrique')
    await page.getByRole('radio', { name: /Compte personnel créé après/ }).check()
    await page.getByLabel('Instructions de test').fill('Chaque jour, ouvrez l’app, cherchez un produit et ajoutez-le au panier.')
    await page.getByLabel('Fonctionnalité 1').fill('Recherche de produits')
    await page.getByLabel('Fonctionnalité 2').fill('Panier')
    await page.getByLabel('Fonctionnalité 3').fill('Suivi de livraison')
    await page.getByRole('radio', { name: 'Non' }).check()
    await page.getByRole('button', { name: 'Enregistrer le brouillon' }).click()
    await page.waitForURL('/mon-compte')

    await page.getByRole('link', { name: 'Devis Offre Plus : Marché Afrique' }).click()
    await expect(page.getByRole('heading', { name: 'Devis Offre Plus' })).toBeVisible()
    await page.getByRole('checkbox', { name: 'Bénin' }).check()
    await page.getByRole('checkbox', { name: 'Fon' }).check()
    await page.getByLabel('Profils de testeurs').fill('Commerçantes de marché, peu habituées aux applications.')
    await page.getByLabel('Scénarios à jouer').fill('Créer un compte et payer par Mobile Money sur un réseau lent.')
    await verifierAccessibilite(page)
    await verifierSansDefilementHorizontal(page)
    await page.getByRole('button', { name: 'Demander un devis' }).click()
    await expect(page.getByText('Votre besoin est envoyé.', { exact: false })).toBeVisible()
    await page.goto('/mon-compte')
    await deconnecter(page)

    await seConnecter(page, 'admin@nakayo.test')
    await page.waitForURL('/admin/tableau-de-bord')
    await page.getByRole('link', { name: 'Devis Offre Plus' }).click()
    const carte = page.getByRole('article', { name: 'Marché Afrique' })
    await expect(carte.getByText('Bénin', { exact: true })).toBeVisible()
    await verifierAccessibilite(page)
    await verifierSansDefilementHorizontal(page)
    await carte.getByLabel('Prix par carte (en $)').fill('149')
    await carte.getByLabel('Prix par Mobile Money (en FCFA)').fill('89400')
    await carte.getByRole('button', { name: 'Proposer ce prix : Marché Afrique' }).click()
    await expect(page.getByText('Prix proposé pour « Marché Afrique ».', { exact: false })).toBeVisible()
    await deconnecter(page)

    await seConnecter(page, 'valide@exemple.com')
    await page.waitForURL('/mon-compte')
    await page.getByRole('link', { name: 'Devis Offre Plus reçu : Marché Afrique' }).click()
    await expect(page.getByRole('region', { name: 'Notre proposition' })).toContainText('149,00 $ US')
    await page.getByRole('link', { name: 'Payer ce devis' }).click()
    await expect(page.getByRole('radio', { name: /Offre Plus \(votre devis\)/ })).toBeChecked()
    await page.getByRole('radio', { name: /Mobile Money/ }).check()
    await page.getByLabel('Numéro Mobile Money').fill('+229 01 97 00 00 01')
    await verifierAccessibilite(page)
    await page.getByRole('button', { name: /^Payer 89\s400 FCFA/ }).click()
    await page.getByRole('button', { name: 'Confirmer le paiement' }).click()
    await page.getByRole('link', { name: 'Retour à mon compte' }).click()
    await expect(page.getByText('Offre Plus')).toBeVisible()
  })
})
